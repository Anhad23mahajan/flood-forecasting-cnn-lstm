"""Insert / refresh the round-2 section and the final 'What is and is not established' section in PROJECT_LOG.md (idempotent).
Sources: completion/LOG_ROUND2_narrative.md (sections 1-7), completion/results/REPORT.md, results_narrative.md, SEVERITY_REPORT.md, log_established.md.
Usage: python completion/build_log.py [--final]   (--final refuses to write while a [PENDING ...] marker is left)"""
import os
import re
import sys

os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FINAL = "--final" in sys.argv


def read(p):
    return open(p, encoding="utf-8").read() if os.path.exists(p) else f"[PENDING: {p} not written yet]"


narr = read("completion/LOG_ROUND2_narrative.md").rstrip()
report = read("completion/results/REPORT.md")
report = re.sub(r"^# .*\n", "", report, count=1)
report = re.sub(r"^## ", "#### ", report, flags=re.M)
sev = read("completion/results/SEVERITY_REPORT.md")
sev = re.sub(r"^# .*\n", "", sev, count=1)
sev = re.sub(r"^## ", "#### ", sev, flags=re.M)
extra = read("completion/results/results_narrative.md").rstrip()
established = read("completion/results/log_established.md").rstrip()

# the mistakes list (section 7 of the narrative) moves to the end; results become sections 8 and 9
parts = narr.split("### 7. Mistakes made in round 2")
head_part, mistakes = parts[0].rstrip(), "### 10. Mistakes made in round 2" + parts[1]
section = (head_part + "\n\n### 7. Results (generated by `completion/g_report.py` from the result files; skill = 1 - SSE_model / SSE_persistence)\n\n"
           "Held-out tiles = tiles of the TRAINING region never used for training (3 folds, every tile held out once); never-seen region = a different flood. Intervals: 95% block bootstraps "
           "(time blocks; tiles x time blocks for the held-out score) - wider than the naive ones because neighbouring windows overlap and each region is ONE event. "
           "Frozen recipe, pre-registered (`completion/PREREGISTRATION.md`).\n\n" + report.strip() + "\n\n" + extra + "\n\n"
           "### 9. Severity, symbolic rules and Grad-CAM on the new encoder (`completion/severity_study.py`; Australia 30 m; 3 tile folds)\n\n" + sev.strip() + "\n\n" + mistakes.strip() + "\n")
section = "<!-- ROUND2 START -->\n" + section + "<!-- ROUND2 END -->\n\n"

p = "PROJECT_LOG.md"
s = open(p, encoding="utf-8").read()
if "<!-- ROUND2 START -->" in s:
    s = re.sub(r"<!-- ROUND2 START -->.*?<!-- ROUND2 END -->\n\n", lambda m: section, s, flags=re.S)
else:
    anchor = "## What is and is not established"
    assert s.count(anchor) == 1
    s = s.replace(anchor, section + anchor)
m = re.search(r"## What is and is not established.*?(?=\n## Local setup notes)", s, re.S)
assert m, "established section not found"
s = s[:m.start()] + "## What is and is not established\n\n" + established + "\n" + s[m.end():]
pend = re.findall(r"\[PENDING[^\]]*\]", s)
if FINAL:
    assert not pend, f"unresolved placeholders: {pend[:5]}"
open(p, "w", encoding="utf-8").write(s)
print("PROJECT_LOG updated | pending markers:", len(pend), "| size:", len(s))
