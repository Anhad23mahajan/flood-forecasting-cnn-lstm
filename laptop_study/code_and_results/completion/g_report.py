"""Turn the raw results into the final tables and the verdicts on the pre-registered hypotheses (completion/PREREGISTRATION.md).
Reads completion/results/runs/*.json (neural runs) and completion/results/baselines_*_n300*.json (baseline ladder); writes completion/results/REPORT.md
and completion/results/report.json.  Missing groups are simply skipped, so it can be run at any time while the queue is still working.
Usage: python completion/g_report.py
"""
import collections
import glob
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import d_aggregate as A  # noqa: E402  (chdirs to the project root)

EXPS = ["E60", "E30", "E480"]
EXP_NAME = {"E60": "Australia -> UK, 60 m", "E30": "Australia -> UK, 30 m", "E480": "Pakistan -> Mozambique, 480 m"}
REG = ["causal", "hybrid", "forced"]
NN = [("v1", "original CNN-LSTM (v1)"), ("local1", "CNN kernel 1 (per pixel)"), ("local", "local CNN 5x5, 4.1k params"), ("local11", "CNN kernel 11"),
      ("clstm", "small ConvLSTM (CNN-LSTM), 4.7k params"), ("clstmf", "ConvLSTM, future rain as side channels (forced only)"), ("v2lin", "heavy ConvLSTM + local path")]
BASE = [("S1", "linear: depth trend only"), ("S3c", "linear: rain + state + trend (>=0)"), ("S5", "2-feature lookup table (depth x last change)"), ("S4c", "per-pixel MLP")]


def fmt(v, ci=None):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "-"
    return f"{v:+.3f}" + (f" [{ci[0]:+.3f}, {ci[1]:+.3f}]" if ci else "")


def main():
    groups, base = A.load_runs(), A.load_baselines()
    out, js = [], {}

    def grp(exp, arch, regime, variant="full", aug=False, blk=False):
        for k, v in groups.items():
            if k[:6] == (exp, arch, regime, variant, aug, blk):
                return sorted(v, key=lambda r: r["fold"])
        return []

    def stat(runs):
        if not A.complete(runs):
            return None
        te = [r["test"]["skill"] for r in runs]
        return dict(test_mean=float(np.mean(te)), test_folds=te, test_ci=A.start_bootstrap(runs), held_pooled=float(A.pooled_skill([r["heldout_windows"] for r in runs])),
                    held_ci=A.tile_bootstrap(runs), held_folds=[r["heldout"]["skill"] for r in runs])

    def bl(exp, regime, key, part, blk=False):
        L = base.get((exp, regime, blk), [])
        return float(np.mean([x[key][part] for x in L if key in x])) if L and all(key in x for x in L) and len(L) == 3 else None

    S = {}
    for exp in EXPS:
        for reg in REG:
            for arch, _ in NN:
                S[(exp, arch, reg)] = stat(grp(exp, arch, reg))

    # ------------------------------------------------------------- headline table per experiment
    out.append("# Results report (generated by completion/g_report.py)\n")
    for exp in EXPS:
        out.append(f"## {exp}: {EXP_NAME[exp]}  (skill vs persistence; mean over 3 tile folds; [95% CI]: bootstrap over start times / tiles)\n")
        out.append("| model | " + " | ".join(f"{r}: never-seen test" for r in REG) + " | " + " | ".join(f"{r}: held-out tiles (neural: pooled; baselines: mean of folds)" for r in REG) + " |")
        out.append("|---|" + "---|" * (2 * len(REG)))
        out.append("| persistence (copy the last frame) | " + " | ".join("0 (by definition)" for _ in range(2 * len(REG))) + " |")
        for key, label in BASE:
            cells = [fmt(bl(exp, r, key, "test")) for r in REG] + [fmt(bl(exp, r, key, "heldout")) for r in REG]
            out.append(f"| {label} | " + " | ".join(cells) + " |")
        _dag_used = []
        for arch, label in NN:
            cells_t, cells_h = [], []
            for r in REG:
                s = S[(exp, arch, r)]
                cells_t.append(fmt(s["test_mean"], s["test_ci"]) if s else "-")
                cells_h.append(fmt(s["held_pooled"], s["held_ci"]) if s else "-")
            if any(c != "-" for c in cells_t + cells_h):
                dag = " \u2020" if any(not r_.get("guard", True) for rg in REG for r_ in grp(exp, arch, rg)) else ""
                _dag_used.append(bool(dag))
                out.append(f"| **{label}{dag}** | " + " | ".join(cells_t + cells_h) + " |")
        if any(_dag_used):
            out.append("\n\u2020 contains runs that were finished with the dead-network check disabled after it aborted them falsely (same seed and recipe; see the table 'Runs aborted by the dead-network guard').")
        out.append("")
    js["headline"] = {f"{e}|{a}|{r}": v for (e, a, r), v in S.items() if v}
    js["baselines"] = {f"{e}|{r}|{k}": {"test": bl(e, r, k, "test"), "heldout": bl(e, r, k, "heldout")}
                       for e in EXPS for r in REG for k in ("S1", "S3c", "S5", "S4c") if bl(e, r, k, "test") is not None}

    # ------------------------------------------------------------- hypotheses
    out.append("## Pre-registered hypotheses\n")
    lines = []
    # H1: clstm and local beat persistence on held-out tiles AND never-seen regions, every regime (95% CI lower bound > 0)
    ok, tot, bad = 0, 0, []
    for arch in ("local", "clstm"):
        for exp in EXPS:
            for reg in REG:
                s = S[(exp, arch, reg)]
                if not s:
                    continue
                tot += 1
                if s["test_ci"][0] > 0 and s["held_ci"][0] > 0:
                    ok += 1
                else:
                    bad.append(f"{arch}/{exp}/{reg} (test CI {s['test_ci'][0]:+.3f}, held-out CI {s['held_ci'][0]:+.3f})")
    lines.append(f"* **H1** (local and clstm beat persistence with both intervals above 0, every regime/experiment): {ok}/{tot} cells pass" + (f"; not passing: {'; '.join(bad)}" if bad else "") + ".")
    # H2: beats best linear baseline S3c on never-seen region
    ok, tot = 0, 0
    for arch in ("local", "clstm"):
        for exp in EXPS:
            for reg in REG:
                s, b = S[(exp, arch, reg)], bl(exp, reg, "S3c", "test")
                if s and b is not None:
                    tot += 1; ok += int(s["test_mean"] > b)
    lines.append(f"* **H2** (beat the best linear baseline S3c on the never-seen region): {ok}/{tot} cells pass.")
    # H2b (added): beat the per-pixel MLP S4c?
    ok, tot, diffs = 0, 0, []
    for arch in ("local", "clstm"):
        for exp in EXPS:
            for reg in REG:
                s, b = S[(exp, arch, reg)], bl(exp, reg, "S4c", "test")
                if s and b is not None:
                    tot += 1; ok += int(s["test_mean"] > b); diffs.append(s["test_mean"] - b)
    if tot:
        lines.append(f"* **H2b** (exploratory, added after seeing the per-pixel baseline: do the CNN/ConvLSTM beat the per-pixel MLP S4c on the never-seen region?): {ok}/{tot} cells; mean difference {np.mean(diffs):+.3f} (range {min(diffs):+.3f} .. {max(diffs):+.3f}).")
    # H3 (pre-registered rule): skill without depth history is lower than with it by MORE THAN the fold-to-fold sd of the full model
    for arch3, var in (("local", "nodepthhist"), ("local", "nohist"), ("clstm", "nodepthhist")):
        rows = []
        for exp in EXPS:
            for reg in REG:
                a, b = grp(exp, arch3, reg, "full"), grp(exp, arch3, reg, var)
                if A.complete(a) and A.complete(b):
                    d = [x["test"]["skill"] - y["test"]["skill"] for x, y in zip(a, b)]
                    sd = float(np.std([x["test"]["skill"] for x in a], ddof=1))
                    rows.append((exp, reg, float(np.mean(d)), sd, float(np.mean(d)) > sd))
        if rows:
            lines.append(f"* **H3** (depth history matters; {arch3} trained {var} vs full, never-seen region): full - {var}, mean over folds (fold sd of the full model): " +
                         "; ".join(f"{e}/{r} {m:+.3f} ({sd:.3f})" for e, r, m, sd, _ in rows) + f". Rule (difference > fold sd) holds in {sum(1 for *_, ok in rows if ok)}/{len(rows)} cells.")
    # H4 (pre-registered rule): recurrence: clstm - local; EQUIVALENT if |mean difference| < 0.02 and the 95% block-bootstrap interval lies inside +-0.03, otherwise the larger model wins
    rows = []
    for exp in EXPS:
        for reg in REG:
            a, b = grp(exp, "clstm", reg), grp(exp, "local", reg)
            if A.complete(a) and A.complete(b):
                d, ci = A.paired_start_bootstrap(a, b)
                verdict = "equivalent" if (abs(d) < 0.02 and ci[0] > -0.03 and ci[1] < 0.03) else ("clstm larger" if d > 0 else "local larger")
                if verdict != "equivalent" and ci[0] < 0 < ci[1]:
                    verdict += " (by the rule, but the interval includes 0)"
                rows.append((exp, reg, d, ci, verdict))
    if rows:
        lines.append("* **H4** (recurrence matters: clstm - local, never-seen region, paired block bootstrap; pre-registered rule): " +
                     "; ".join(f"{e}/{r} {d:+.3f} [{ci[0]:+.3f}, {ci[1]:+.3f}] -> {v}" for e, r, d, ci, v in rows) + ".")
    # H5: ordering
    ok, tot = 0, 0
    for arch, _ in NN:
        for exp in EXPS:
            v = [S[(exp, arch, r)] for r in REG]
            if all(v):
                tot += 1; ok += int(v[0]["test_mean"] <= v[1]["test_mean"] <= v[2]["test_mean"])
    if tot:
        lines.append(f"* **H5** (causal <= hybrid <= forced on the never-seen region, means): {ok}/{tot} (arch, experiment) cases hold. Caution (code review F4): the recurrent model reads the forced rain as five extra steps AFTER the observed history, which handicaps it; a failure for clstm is an input-layout effect, not evidence about rain physics.")
    # H6: blocked vs standard held-out
    rows = []
    for exp in EXPS:
        for arch in ("local", "clstm"):
            a, b = grp(exp, arch, "hybrid"), grp(exp, arch, "hybrid", blk=True)
            if A.complete(a) and A.complete(b):
                pa = A.pooled_skill([r["heldout_windows"] for r in a]); pb = A.pooled_skill([r["heldout_windows"] for r in b])
                rows.append((exp, arch, pa, pb))
    if rows:
        lines.append("* **H6** (strict space+time hold-out within 0.05 of the tile-only hold-out): " + "; ".join(f"{e}/{a}: {pa:+.3f} -> {pb:+.3f}" for e, a, pa, pb in rows) +
                     f". Pass in {sum(1 for *_, pa, pb in rows if abs(pa - pb) < 0.05)}/{len(rows)}.")
    out += lines + [""]
    js["hypotheses"] = lines

    # ------------------------------------------------------------- test-time ablations (mean over folds), hybrid
    out.append("## What the trained models use (test-time ablations, never-seen region, hybrid regime, mean over folds)\n")
    keys = ["none", "rain_removed", "terrain_removed", "depth_hist_scrambled", "depth_hist_frozen", "rain_hist_frozen", "rain_shifted_earlier"]
    out.append("| experiment | model | " + " | ".join(keys) + " |")
    out.append("|---|---|" + "---|" * len(keys))
    for exp in EXPS:
        for arch, label in NN:
            runs = grp(exp, arch, "hybrid")
            if len(runs) == 3 and all(r.get("ablation_test") for r in runs):
                out.append(f"| {exp} | {label} | " + " | ".join(f"{np.mean([r['ablation_test'][k] for r in runs if k in r['ablation_test']]):+.3f}" if all(k in r['ablation_test'] for r in runs) else "-" for k in keys) + " |")
    out.append("")

    # ------------------------------------------------------------- training-time ablations
    out.append("## Training-time ablations (models trained without one ingredient; never-seen region skill, mean over folds)\n")
    variants = ["full", "nodepthhist", "norainhist", "nohist", "norain", "noterrain"]
    out.append("| experiment | model | regime | " + " | ".join(variants) + " |")
    out.append("|---|---|---|" + "---|" * len(variants))
    for arch_t, lab_t in (("local", "local CNN"), ("clstm", "ConvLSTM")):
        for exp in EXPS:
            for reg in REG:
                cells = []
                for v in variants:
                    r = grp(exp, arch_t, reg, v)
                    cells.append(f"{np.mean([x['test']['skill'] for x in r]):+.3f}" if A.complete(r) else "-")
                if any(c != "-" for c in cells[1:]):
                    out.append(f"| {exp} | {lab_t} | {reg} | " + " | ".join(cells) + " |")
    out.append("")

    out.append("## What the models do with KNOWN future rain (test-time ablations, forced regime, never-seen region, mean over folds)\n")
    keys_f = ["none", "rain_removed", "future_rain_removed", "depth_hist_frozen"]
    out.append("| experiment | model | " + " | ".join(keys_f) + " |")
    out.append("|---|---|" + "---|" * len(keys_f))
    for exp in EXPS:
        for arch, label in NN:
            runs = grp(exp, arch, "forced")
            if len(runs) == 3 and all(r.get("ablation_test") and "future_rain_removed" in r["ablation_test"] for r in runs):
                out.append(f"| {exp} | {label} | " + " | ".join(f"{np.mean([r['ablation_test'][k] for r in runs]):+.3f}" for k in keys_f) + " |")
    out.append("")

    # ------------------------------------------------------------- exploratory batches (per-fold records; never merged into the headline groups)
    extra = A.load_runs(extra=True)

    def every(exp, arch, regime, variant="full", blocked=False):
        """(run, is_frozen) for every final-size run of this configuration, frozen recipe or not."""
        res = []
        for fl, gs in ((True, A.load_runs()), (False, extra)):
            for k, v in gs.items():
                if k[:6] == (exp, arch, regime, variant, False, blocked):
                    res += [(r, fl) for r in v]
        return sorted(res, key=lambda t: (t[0]["fold"], not t[1], t[0]["seed"]))

    out.append("## Exploratory: ConvLSTM with the future rain as side channels (clstmf, forced regime), per fold (frozen recipe unless marked)\n")
    out.append("| experiment | model | fold | seed | never-seen skill | held-out tiles skill | note |")
    out.append("|---|---|---|---|---|---|---|")
    for exp in ("E60", "E30", "E480"):
        for arch in ("clstm", "clstmf"):
            seen = set()
            for r, fl in every(exp, arch, "forced"):
                seen.add((r["fold"], fl))
                note = ("guard disabled after a false abort (post hoc; identical recipe and seed)" if (fl and not r.get("guard", True)) else "") if fl else (f"RETRY after the frozen-seed run was aborted by the guard (post hoc): seed {r['seed']}" + (f", learning rate {float(r.get('lr', 1e-3)):g}" if abs(float(r.get('lr', 1e-3)) - 1e-3) > 1e-12 else ""))
                out.append(f"| {exp} | {arch} | {r['fold']} | {r['seed']} | {fmt(r['test']['skill'])} | {fmt(r['heldout']['skill'])} | {note} |")
            if arch == "clstmf":
                for f in range(3):
                    lf = f"completion/logs/runs/{exp}_clstmf_forced_full_f{f}of3_s{1000 + 10 * f + 3}_ep30.log"
                    if (f, True) not in seen and os.path.exists(lf):
                        txt = open(lf, errors="replace").read()
                        if "DEAD NETWORK" in txt:
                            ep = txt.split("DEAD NETWORK after epoch ")[-1].split(":")[0]
                            out.append(f"| {exp} | clstmf | {f} | {1000 + 10 * f + 3} | - | - | ABORTED by the dead-network guard after epoch {ep} (a false alarm: see the guard-disabled row); no result of its own |")
                        for tag, sd_, extra_ in (("retry", 4, ""), ("retry2", 5, ", learning rate 0.0005")):
                            lf2 = f"completion/logs/runs/{exp}_clstmf_forced_{tag}_f{f}.log"
                            if os.path.exists(lf2) and "DEAD NETWORK" in open(lf2, errors="replace").read():
                                ep2 = open(lf2, errors="replace").read().split("DEAD NETWORK after epoch ")[-1].split(":")[0]
                                out.append(f"| {exp} | clstmf | {f} | {1000 + 10 * f + sd_} | - | - | RETRY (post hoc){extra_}: also ABORTED by the guard after epoch {ep2}; not pursued further |")
    out.append("")

    out.append("## The original model (v1) against the final models, same folds, hybrid regime, per fold (never-seen / held-out tiles)\n")
    out.append("| experiment | fold | original v1 | local CNN | small ConvLSTM |")
    out.append("|---|---|---|---|---|")
    for exp in EXPS:
        for f in range(3):
            cells = []
            v1s = [(r, fl) for r, fl in every(exp, "v1", "hybrid") if r["fold"] == f]
            txt = "; ".join(f"{fmt(r['test']['skill'])} / {fmt(r['heldout']['skill'])}" + ("" if r.get("guard", True) else " (guard disabled: the old check looked at the earliest, near-static windows and aborted it falsely)") for r, fl in v1s)
            for arch in ("local", "clstm"):
                rr = [r for r in grp(exp, arch, "hybrid") if r["fold"] == f]
                cells.append(f"{fmt(rr[0]['test']['skill'])} / {fmt(rr[0]['heldout']['skill'])}" if rr else "-")
            if txt or any(c != "-" for c in cells):
                out.append(f"| {exp} | {f} | {txt or '-'} | " + " | ".join(cells) + " |")
    out.append("")

    out.append("## Exploratory: optimisation robustness (batch 8, learning rate 3e-3, hybrid; a deviation from the frozen recipe)\n")
    out.append("| experiment | model | frozen recipe: never-seen / held-out | batch 8, lr 3e-3: never-seen / held-out | folds |")
    out.append("|---|---|---|---|---|")
    for exp in EXPS:
        for arch in ("local", "clstm"):
            fz = stat(grp(exp, arch, "hybrid"))
            op = [r for r, fl in every(exp, arch, "hybrid") if not fl and int(r.get("batch", 1)) == 8 and abs(float(r.get("lr", 1e-3)) - 3e-3) < 1e-9]
            if op:
                done_ok = A.complete(op)
                a_ = f"{fmt(fz['test_mean'])} / {fmt(fz['held_pooled'])}" if fz else "-"
                b_ = (f"{fmt(float(np.mean([r['test']['skill'] for r in op])))} / {fmt(float(A.pooled_skill([r['heldout_windows'] for r in op])))}" if done_ok
                      else "incomplete: " + ", ".join(f"f{r['fold']} {fmt(r['test']['skill'])}/{fmt(r['heldout']['skill'])}" for r in op))
                out.append(f"| {exp} | {arch} | {a_} | {b_} | {len(op)} |")
    out.append("")

    out.append("## Exploratory: seed repeats of the local CNN (hybrid; the frozen-seed run plus seeds 11-14)\n")
    out.append("| experiment | fold | never-seen skill per seed (frozen seed first) | sd over seeds | held-out tiles skill per seed (seed AND data draw change) | sd over seeds |")
    out.append("|---|---|---|---|---|---|")
    seed_sd, fold_sd = {}, {}
    for exp in EXPS:
        per_fold_t, per_fold_h, within_t, within_h = [], [], [], []
        for f in range(3):
            rs = [r for r, fl in every(exp, "local", "hybrid") if r["fold"] == f and int(r.get("batch", 1)) == 1 and abs(float(r.get("lr", 1e-3)) - 1e-3) < 1e-9]
            if len(rs) >= 2:
                t = [r["test"]["skill"] for r in rs]
                h = [r["heldout"]["skill"] for r in rs]
                out.append(f"| {exp} | {f} | " + " ".join(f"{x:+.3f}" for x in t) + f" | {np.std(t, ddof=1):.3f} | " + " ".join(f"{x:+.3f}" for x in h) + f" | {np.std(h, ddof=1):.3f} |")
                per_fold_t.append(float(np.mean(t))); per_fold_h.append(float(np.mean(h)))
                within_t.append(float(np.std(t, ddof=1))); within_h.append(float(np.std(h, ddof=1)))
        if len(per_fold_t) == 3:
            seed_sd[exp] = (float(np.mean(within_t)), float(np.mean(within_h)))
            fold_sd[exp] = (float(np.std(per_fold_t, ddof=1)), float(np.std(per_fold_h, ddof=1)))
    for exp in seed_sd:
        out.append(f"\n**{exp}:** sd over seeds within a fold (mean of the 3 folds): never-seen {seed_sd[exp][0]:.3f}, held-out tiles {seed_sd[exp][1]:.3f}; sd of the seed-averaged skill over the 3 folds: never-seen {fold_sd[exp][0]:.3f}, held-out tiles {fold_sd[exp][1]:.3f}.")
    js["seed_repeats"] = {"seed_sd": seed_sd, "fold_sd": fold_sd}
    out.append("")

    out.append("## Exploratory: the strict space+time split on Pakistan (E480, local CNN, fold 0): other seeds and the batch-8 / lr 3e-3 recipe\n")
    out.append("| recipe | seed | held-out (tiles AND a time block hidden) | never-seen (Mozambique) |")
    out.append("|---|---|---|---|")
    rs_s = [(r, fl) for r, fl in every("E480", "local", "hybrid", blocked=True) if r["fold"] == 0]
    for r, fl in rs_s:
        rec = "frozen (batch 1, lr 1e-3)" if (int(r.get("batch", 1)) == 1 and abs(float(r.get("lr", 1e-3)) - 1e-3) < 1e-12) else f"batch {int(r.get('batch', 1))}, lr {float(r.get('lr', 1e-3)):g}"
        out.append(f"| {rec} | {r['seed']} | {fmt(r['heldout']['skill'])} | {fmt(r['test']['skill'])} |")
    out.append("")

    # ------------------------------------------------------------- learning curve and training length (final-size runs of other n_train / epochs; d_aggregate filters those out)
    def raw_runs(exp, arch, regime="hybrid", n_train=None, epochs=30, variant="full"):
        res = []
        for f in sorted(glob.glob("completion/results/runs/*.json")):
            r = json.load(open(f))
            if (r["exp"], r.get("arch", "v1"), r["regime"], r["variant"], bool(r.get("augment", False)), bool(r.get("blocked", False))) != (exp, arch, regime, variant, False, False):
                continue
            if r.get("test") is None or r["epochs"] != epochs or int(r.get("batch", 1)) != 1 or abs(float(r.get("lr", 1e-3)) - 1e-3) > 1e-12 or (n_train is not None and r["n_train"] != n_train):
                continue
            res.append(r)
        return res

    def fold_mean(rs, key="test", frozen_seed=None):
        by = {}
        for r in rs:
            if frozen_seed is not None and (r["seed"] == 1000 + 10 * r["fold"] + r["K"]) != frozen_seed:
                continue
            by[r["fold"]] = r
        return (float(np.mean([by[f][key]["skill"] for f in range(3)])), [by[f][key]["skill"] for f in range(3)]) if len(by) == 3 else None

    def base_n(exp, key, n, part="test"):
        v = []
        for f in range(3):
            p = f"completion/results/baselines_{exp}_hybrid_f{f}of3_n{n}.json"
            if os.path.exists(p):
                d = json.load(open(p))
                if key in d:
                    v.append(d[key][part]["skill"] if isinstance(d[key][part], dict) else d[key][part])
        return float(np.mean(v)) if len(v) == 3 else None

    NS = (25, 50, 100, 300, 600)
    out.append("## Exploratory: learning curve (never-seen skill vs number of training windows; hybrid; mean over 3 folds; the frozen recipe uses 300; FIXED 30 epochs, so the number of optimiser steps grows with n - see the equal-steps table below)\n")
    out.append("| experiment | model | " + " | ".join(f"n = {n}" for n in NS) + " |")
    out.append("|---|---|" + "---|" * len(NS))
    lc = {}
    for exp in EXPS:
        row_cnn = []
        for n in NS:
            rs = raw_runs(exp, "local", n_train=n)
            fm = fold_mean(rs, frozen_seed=True if n == 300 else False)
            row_cnn.append(fm[0] if fm else None)
        out.append(f"| {exp} | local CNN | " + " | ".join(fmt(v) for v in row_cnn) + " |")
        lc[f"{exp}|local"] = row_cnn
        for key, lab in (("S1", "linear trend"), ("S5", "lookup table"), ("S4c", "per-pixel MLP")):
            row = [base_n(exp, key, n) for n in NS]
            if any(v is not None for v in row):
                out.append(f"| {exp} | {lab} | " + " | ".join(fmt(v) for v in row) + " |")
                lc[f"{exp}|{key}"] = row
    js["learning_curve"] = lc
    out.append("")
    out.append("## Exploratory: learning curve with EQUAL optimiser steps (local CNN, hybrid, never-seen, mean of 3 folds; steps = epochs x windows)\n")
    out.append("| experiment | n=300, 30 epochs (9,000 steps) | n=600, 15 epochs (9,000 steps) | n=300, 60 epochs (18,000 steps) | n=600, 30 epochs (18,000 steps) |")
    out.append("|---|---|---|---|---|")
    for exp in EXPS:
        c1 = fold_mean(raw_runs(exp, "local", n_train=300, epochs=30), frozen_seed=True)
        c2 = fold_mean(raw_runs(exp, "local", n_train=600, epochs=15))
        c3 = fold_mean(raw_runs(exp, "local", n_train=300, epochs=60))
