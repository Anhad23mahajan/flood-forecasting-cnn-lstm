    # ------------------------------------------------------------- where the failures are: the windows at the very start of the flood (start index 0)
    out.append("## Where the failures are: the windows at the very START of the flood (start index 0)\n")
    out.append("Pooled over the 3 folds. 'start 0' = windows whose first observed frame is the first frame of the simulation (the flood is just beginning).\n")
    out.append("| what | windows (of which start 0) | skill, all windows | share of the model's squared error in the start-0 windows | skill without the start-0 windows |")
