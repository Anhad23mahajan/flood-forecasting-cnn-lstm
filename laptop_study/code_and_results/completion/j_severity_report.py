"""Summarise completion/results/severity/SEV_*.json (severity_study.py) into tables: capsule vs dense head, threshold baselines, the symbolic rule layer,
whether its reasons are true, and Grad-CAM faithfulness / stability.  Usage: python completion/j_severity_report.py   -> completion/results/SEVERITY_REPORT.md"""
import collections
import glob
import json
import os

import numpy as np

os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RNG = np.random.default_rng(7)
runs = collections.defaultdict(list)
for f in sorted(glob.glob("completion/results/severity/SEV_*.json")):
    r = json.load(open(f))
    seed_default = 2000 + 10 * r["fold"] + r["K"]
    key = (r["regime"], r["head"], bool(r.get("augment", False)))
    if r["seed"] == seed_default:
        runs[key].append(r)
    else:
        runs[key + ("seed%d" % r["seed"],)].append(r)
out = ["# Severity / rules / Grad-CAM report (generated by completion/j_severity_report.py)\n"]


def pooled(rs, split, field):
    """Accuracy pooled over folds, from the per-window arrays (natural / balanced windows)."""
    tot = sum(len(r["eval"][split]["per_window"]["true"]) for r in rs)
    if field == "acc":
        return sum(np.sum(np.array(r["eval"][split]["per_window"]["cls"]) == np.array(r["eval"][split]["per_window"]["true"])) for r in rs) / tot
    if field == "base":
        return sum(np.sum(np.array(r["eval"][split]["per_window"]["base"]) == np.array(r["eval"][split]["per_window"]["true"])) for r in rs) / tot
    if field == "fc":
        return sum(np.sum(np.array(r["eval"][split]["per_window"]["pcls"]) == np.array(r["eval"][split]["per_window"]["true"])) for r in rs) / tot


def changing(rs):
    n = c = f = 0
    for r in rs:
        w = r["eval"]["natural"]["per_window"]
        t, b, p, q = (np.array(w[k]) for k in ("true", "base", "cls", "pcls"))
        m = t != b
        n += int(m.sum()); c += int(np.sum(p[m] == t[m])); f += int(np.sum(q[m] == t[m]))
    return n, c, f


out.append("## Severity accuracy on held-out tiles (3 folds pooled; the natural set keeps the real class mix, the balanced set has 60 windows per class)\n")
out.append("| regime | head | aug | folds | natural acc | balanced acc | last-frame threshold (nat / bal) | forecast threshold (nat) | class-changing windows: n, model right, forecast-threshold right |")
out.append("|---|---|---|---|---|---|---|---|---|")
for key, rs in sorted(runs.items(), key=lambda kv: str(kv[0])):
    if len(key) > 3:
        continue
    n, c, f = changing(rs)
    out.append(f"| {key[0]} | {key[1]} | {'y' if key[2] else 'n'} | {len(rs)} | {pooled(rs, 'natural', 'acc'):.3f} | {pooled(rs, 'balanced', 'acc'):.3f} | "
               f"{pooled(rs, 'natural', 'base'):.3f} / {pooled(rs, 'balanced', 'base'):.3f} | {pooled(rs, 'natural', 'fc'):.3f} | {n}, {c}, {f} |")
out.append("")

# paired capsule - dense (same windows: identical seeds and sampling)
for reg in ("hybrid", "causal", "forced"):
    for aug in (False, True):
        a, b = runs.get((reg, "capsule", aug), []), runs.get((reg, "dense", aug), [])
        if len(a) == 3 and len(b) == 3:
            d = []
            for ra, rb in zip(sorted(a, key=lambda r: r["fold"]), sorted(b, key=lambda r: r["fold"])):
                wa, wb = ra["eval"]["natural"]["per_window"], rb["eval"]["natural"]["per_window"]
                if wa["idx"] == wb["idx"]:
                    d += list((np.array(wa["cls"]) == np.array(wa["true"])).astype(float) - (np.array(wb["cls"]) == np.array(wb["true"])).astype(float))
            if d:
                d = np.array(d)
                bs = [d[RNG.integers(0, len(d), len(d))].mean() for _ in range(2000)]
                out.append(f"* capsule - dense accuracy ({reg}{', augmented' if aug else ''}, natural windows, paired): {d.mean():+.3f} [95% CI {np.percentile(bs, 2.5):+.3f}, {np.percentile(bs, 97.5):+.3f}] over {len(d)} windows.")
out.append("")

out.append("## Symbolic rule layer (natural held-out windows, pooled over folds)\n")
out.append("| regime | head | thresholds | accuracy before -> after | windows changed | fixed a wrong answer | broke a right one | rules triggered |")
out.append("|---|---|---|---|---|---|---|---|")
for key, rs in sorted(runs.items(), key=lambda kv: str(kv[0])):
    if len(key) > 3 or not rs or "rules" not in rs[0]:
        continue
    for nm in ("original_thresholds", "recalibrated_on_fold_training_windows"):
        n = sum(r["eval"]["natural"]["n"] for r in rs)
        b = sum(r["rules"][nm]["acc_before"] * r["eval"]["natural"]["n"] for r in rs) / n
        a = sum(r["rules"][nm]["acc_after"] * r["eval"]["natural"]["n"] for r in rs) / n
        out.append(f"| {key[0]} | {key[1]}{'+aug' if key[2] else ''} | {nm.split('_')[0]} | {b:.3f} -> {a:.3f} | {sum(r['rules'][nm]['n_changed'] for r in rs)} | "
                   f"{sum(r['rules'][nm]['n_fixed'] for r in rs)} | {sum(r['rules'][nm]['n_broke'] for r in rs)} | {sum(r['rules'][nm]['n_triggered'] for r in rs)} |")
out.append("")
out.append("Are the rule reasons TRUE statements? (the stated depth trend is the model's predicted patch-mean rate; 'true' = same sign as the actual rate)\n")
out.append("| regime | head | sign agreement predicted vs actual trend | 'rising' claims true | 'receding' claims true |")
out.append("|---|---|---|---|---|")
for key, rs in sorted(runs.items(), key=lambda kv: str(kv[0])):
    if len(key) > 3 or not rs or "rules" not in rs[0]:
        continue
    rt = [r["rules"]["reason_truth"] for r in rs]
    g = lambda k: np.mean([x[k] for x in rt if x.get(k) is not None]) if any(x.get(k) is not None for x in rt) else float("nan")
    out.append(f"| {key[0]} | {key[1]}{'+aug' if key[2] else ''} | {g('sign_agreement_rate_predicted_vs_true_depth_trend'):.3f} | {g('rising_claims_true'):.3f} | {g('receding_claims_true'):.3f} |")
out.append("")

out.append("## Grad-CAM (40 fixed held-out windows per model, at the shared encoder's hidden map; hot pixels = the evidence for the target)\n")
out.append("Two maps: 'depth' (target = predicted depth summed over all leads) and 'severity' (target = the predicted class score of the capsule / dense head). Deletion removes the depth + rain history at the "
           "top-10% (positive-heat) pixels and is compared with (a) random pixels of the same wet/dry mix and (b) the same mask moved 40 px.\n")
out.append("| regime | head | map | wet hotter than dry (share of windows) | median wet/dry ratio | mean effect: top / random / moved | top beats random | top beats both controls |")
out.append("|---|---|---|---|---|---|---|---|")
for key, rs in sorted(runs.items(), key=lambda kv: str(kv[0])):
    if len(key) > 3 or not rs or "gradcam" not in rs[0] or "depth" not in rs[0]["gradcam"]:
        continue
    for kd in ("depth", "severity"):
        g = [r_["gradcam"][kd] for r_ in rs if r_["gradcam"][kd]["deletion_effect_top"] is not None]
        if not g:
            continue
        m = lambda k: np.mean([x[k] for x in g])
        out.append(f"| {key[0]} | {key[1]}{'+aug' if key[2] else ''} | {kd} | {m('frac_windows_wet_hotter'):.2f} | {m('median_wet_dry_ratio'):.2f} | "
                   f"{m('deletion_effect_top'):.3f} / {m('deletion_effect_random'):.3f} / {m('deletion_effect_rolled'):.3f} | {m('frac_top_exceeds_random'):.2f} | {m('frac_top_exceeds_both'):.2f} |")
out.append("")
for head in ("capsule", "dense"):
    a_ = [r_ for r_ in runs.get(("hybrid", head, False), []) if r_["fold"] == 0]
    b_ = runs.get(("hybrid", head, False, "seed9"), [])
    if a_ and b_:
        ca = np.load(f"completion/results/severity/{a_[0]['id']}_cams.npz")
        cb = np.load(f"completion/results/severity/{b_[0]['id']}_cams.npz")
        if list(ca["idx"]) == list(cb["idx"]):
            from scipy.stats import spearmanr
            for kd, nm in (("cams_depth", "depth"), ("cams_sev", "severity")):
                rho = [spearmanr(x.astype(float).ravel(), y.astype(float).ravel())[0] for x, y in zip(ca[kd], cb[kd])]
                out.append(f"* Grad-CAM stability across two training seeds ({head} head, fold 0, same 40 windows, {nm} map): median Spearman correlation {np.nanmedian(rho):.2f} (25-75%: {np.nanpercentile(rho, 25):.2f} .. {np.nanpercentile(rho, 75):.2f}).")
md = "\n".join(out)
open("completion/results/SEVERITY_REPORT.md", "w", encoding="utf-8").write(md)
print(md)
